/// Result header shared by all fallible ABI operations.
#[repr(C)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RoupCallResult {
    pub status: RoupStatus,
    pub reserved: u32,
    pub error: RoupErrorHandle,
}

impl RoupCallResult {
    #[must_use]
    pub const fn success() -> Self {
        Self {
            status: RoupStatus::OK,
            reserved: 0,
            error: RoupErrorHandle::INACTIVE,
        }
    }

    #[must_use]
    pub(crate) const fn failure(status: RoupStatus, error: RoupErrorHandle) -> Self {
        Self {
            status,
            reserved: 0,
            error,
        }
    }
}

/// Result of a fallible ABI operation returning a `u32` value.
#[repr(C)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RoupU32Result {
    pub result: RoupCallResult,
    pub value: u32,
    pub reserved: u32,
}

impl RoupU32Result {
    pub(crate) const fn success(value: u32) -> Self {
        Self {
            result: RoupCallResult::success(),
            value,
            reserved: 0,
        }
    }

    pub(crate) const fn failure(status: RoupStatus, error: RoupErrorHandle) -> Self {
        Self {
            result: RoupCallResult::failure(status, error),
            value: 0,
            reserved: 0,
        }
    }
}

