/// Numeric status returned by every fallible C ABI operation.
///
/// This is a transparent integer rather than a Rust enum, so an unknown value
/// received from foreign code can never create an invalid Rust enum.
#[repr(transparent)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RoupStatus(pub u32);

impl RoupStatus {
    pub const OK: Self = Self(0);
    pub const INVALID_ARGUMENT: Self = Self(1);
    pub const INVALID_UTF8: Self = Self(2);
    pub const BUFFER_TOO_SMALL: Self = Self(3);
    pub const INVALID_HANDLE: Self = Self(4);
    pub const STALE_HANDLE: Self = Self(5);
    pub const PARSE_ERROR: Self = Self(6);
    pub const INTERNAL_ERROR: Self = Self(7);

    #[must_use]
    pub const fn is_ok(self) -> bool {
        self.0 == Self::OK.0
    }
}

macro_rules! define_handle {
    ($name:ident) => {
        #[repr(C)]
        #[derive(Clone, Copy, Debug, Eq, PartialEq)]
        pub struct $name {
            pub generation: u64,
            pub index: u64,
        }

        impl $name {
            pub const INACTIVE: Self = Self {
                generation: 0,
                index: 0,
            };

            pub(crate) const fn active(index: u32, generation: u64) -> Self {
                Self {
                    generation,
                    index: index as u64,
                }
            }

            #[must_use]
            pub const fn is_active(self) -> bool {
                self.generation != 0
            }
        }
    };
}

